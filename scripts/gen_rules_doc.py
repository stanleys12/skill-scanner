#!/usr/bin/env python3
"""Write docs/RULES.md, a table of every detection rule. Run: python3 scripts/gen_rules_doc.py

tests/run_tests.py fails if the committed file is out of sync with scanner/rules.py.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from scanner.rules import RULES  # noqa: E402

SEV_ORDER = {"high": 0, "medium": 1, "low": 2, "info": 3}
OUT = os.path.join(ROOT, "docs", "RULES.md")


def render():
    rows = sorted(RULES, key=lambda r: (SEV_ORDER.get(r.severity, 9), r.category, r.id))
    lines = ["# Detection rules", "",
             "Generated by `scripts/gen_rules_doc.py` from `scanner/rules.py`; do not edit by hand.", "",
             f"{len(rows)} rules.", "",
             "| id | category | severity | why |", "| --- | --- | --- | --- |"]
    for r in rows:
        lines.append(f"| `{r.id}` | {r.category} | {r.severity} | {r.why.replace('|', '\\|')} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(render())
